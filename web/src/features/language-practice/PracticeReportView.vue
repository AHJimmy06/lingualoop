<script setup lang="ts">
import { computed, onBeforeUnmount, onMounted, ref } from 'vue'
import { useRoute } from 'vue-router'
import { authSession } from '../../auth-session'
import {
  LanguagePracticeClient,
  LanguagePracticeClientError,
  type LanguagePracticeReport,
} from './language-practice-client'

const route = useRoute()
const client = new LanguagePracticeClient(authSession)
const sessionId = computed(() => {
  const value = route.params.sessionId
  return Array.isArray(value) ? (value[0] ?? '') : (value ?? '')
})
const report = ref<LanguagePracticeReport | null>(null)
const loading = ref(false)
const errorKind = ref<LanguagePracticeClientError['kind'] | null>(null)
let disposed = false
let requestInFlight = false

async function loadReport(): Promise<void> {
  if (disposed || requestInFlight || report.value) return
  requestInFlight = true
  loading.value = true
  errorKind.value = null
  try {
    const result = await client.getOrCreateReport(sessionId.value)
    if (!disposed) report.value = result
  } catch (error) {
    if (!disposed) {
      errorKind.value = error instanceof LanguagePracticeClientError ? error.kind : 'unavailable'
    }
  } finally {
    requestInFlight = false
    if (!disposed) loading.value = false
  }
}

function retry(): void {
  if (errorKind.value !== null) void loadReport()
}

onMounted(() => { void loadReport() })
onBeforeUnmount(() => { disposed = true })
</script>

<template>
  <main class="report-shell" aria-labelledby="report-title">
    <header class="page-heading">
      <div>
        <p class="eyebrow">Practice complete</p>
        <h1 id="report-title">Your practice report</h1>
        <p>Review saved evidence from your session and choose what to practice next.</p>
      </div>
    </header>

    <section v-if="loading" class="feedback" role="status" aria-live="polite">
      Preparing your report…
    </section>

    <section v-else-if="errorKind" class="feedback error" role="alert">
      <h2>We could not load your report</h2>
      <p v-if="errorKind === 'conflict'">This session is still in progress. Return to your session and finish practicing before viewing its report.</p>
      <p v-else-if="errorKind === 'not-found'">This practice session could not be found. Return to setup to start a new practice session.</p>
      <p v-else-if="errorKind === 'invalid-input'">This session link is not valid. Return to setup to start a new practice session.</p>
      <p v-else>The session remains saved. You can try loading its report again.</p>
      <RouterLink v-if="errorKind === 'conflict'" :to="`/language-practice/sessions/${sessionId}`" class="secondary-button">Return to session</RouterLink>
      <button v-else-if="errorKind !== 'not-found' && errorKind !== 'invalid-input'" type="button" class="secondary-button" :disabled="loading" @click="retry">Try again</button>
    </section>

    <template v-else-if="report">
      <section class="report-card" aria-labelledby="summary-title">
        <h2 id="summary-title">Performance summary</h2>
        <p>{{ report.summary }}</p>
        <p class="report-note">This report is generated from saved session evidence. It was not generated by AI.</p>
      </section>

      <section class="report-section" aria-labelledby="corrections-title">
        <div>
          <h2 id="corrections-title">Corrections from your turns</h2>
          <p class="muted">Only corrections supported by saved session evidence appear here.</p>
        </div>
        <div v-if="report.corrections.length" class="report-list">
          <article v-for="correction in report.corrections" :key="correction.sequence" class="report-card">
            <p class="eyebrow">Turn {{ correction.sequence }}</p>
            <dl>
              <div><dt>Original</dt><dd>{{ correction.original }}</dd></div>
              <div><dt>Suggested correction</dt><dd>{{ correction.correctedPhrase }}</dd></div>
              <div><dt>Explanation</dt><dd>{{ correction.explanation }}</dd></div>
            </dl>
          </article>
        </div>
        <p v-else class="empty-state">No evidence-backed corrections were available for this session.</p>
      </section>

      <div class="report-columns">
        <section class="report-card" aria-labelledby="strengths-title">
          <h2 id="strengths-title">Observed strengths</h2>
          <ul v-if="report.strengths.length"><li v-for="strength in report.strengths" :key="strength">{{ strength }}</li></ul>
          <p v-else class="muted">There was not enough completed-turn evidence to identify strengths.</p>
        </section>
        <section class="report-card" aria-labelledby="recommendations-title">
          <h2 id="recommendations-title">Next practice</h2>
          <ul v-if="report.recommendations.length"><li v-for="recommendation in report.recommendations" :key="recommendation">{{ recommendation }}</li></ul>
          <p v-else class="muted">No additional recommendations are available for this session.</p>
        </section>
      </div>
    </template>

    <section v-else class="empty-state" role="status">No report is available for this session.</section>

    <nav class="report-actions" aria-label="Practice navigation">
      <RouterLink to="/language-practice" class="primary-link">Return to practice setup</RouterLink>
    </nav>
  </main>
</template>


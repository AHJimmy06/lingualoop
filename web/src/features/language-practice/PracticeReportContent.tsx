import { ArrowUpRight } from 'lucide-react';
import { ParameterCoverageView } from './ParameterCoverageView';
import { Button } from '../../components/ui/button';
import { ReportLearningNotes } from './ReportLearningNotes';
import { ReportSpanishExplanation } from './ReportSpanishExplanation';
import { ReportSpeechButton } from './ReportSpeechButton';
import type { LanguagePracticeReport, ReportLearningSupport, SessionDetail } from './language-practice-client';

const topicSearchTerms: Record<SessionDetail['topic'], string> = {
  travel: 'travel situations',
  work: 'workplace conversations',
  studies: 'school and university conversations',
  'everyday-conversation': 'everyday conversations',
};

function youtubeSearchUrl(session: SessionDetail, report: LanguagePracticeReport): string {
  // Practice requirements are teacher-authored goals, never transcript-derived personal text.
  const goals = (report.parameterCoverage ?? []).slice(0, 2).map(item => item.requirement)
    .map(value => value.normalize('NFKC').replace(/[^\p{L}\p{N}\s'-]/gu, ' ').replace(/\s+/g, ' ').trim().slice(0, 100))
    .filter(Boolean).join(' ');
  const query = `English ${topicSearchTerms[session.topic]} ${goals} conversation practice CEFR ${session.level} video`;
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(query)}`;
}

/** Saved report presentation: data loading remains in the route and audio in its dedicated control. */
export function PracticeReportContent({ report, session = null, turnsUnavailable = false, learningSupport = null, supportLoading = false, supportError, onLoadSupport }: {
  report: LanguagePracticeReport;
  session?: SessionDetail | null;
  turnsUnavailable?: boolean;
  learningSupport?: ReportLearningSupport | null;
  supportLoading?: boolean;
  supportError?: string;
  onLoadSupport?: () => void;
}) {
  return <div className="@container/report grid min-w-0 gap-6 [overflow-wrap:anywhere]">
    <section className="min-w-0 rounded-xl border bg-card p-5 shadow-sm sm:p-7" aria-labelledby="summary-title">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div><h2 id="summary-title" className="text-lg font-semibold">Performance summary</h2>
          <p className="mt-3 text-sm leading-6 text-muted-foreground">{report.summary}</p></div>
        <span className="rounded-full bg-primary/10 px-3 py-1.5 text-xs font-medium text-primary">{report.generatedWithAi ? 'AI-assisted draft' : 'Saved-session report'}</span>
      </div>
      <p className="mt-5 border-t pt-4 text-sm leading-6 text-muted-foreground">{report.generatedWithAi
        ? 'AI observations use saved STT transcripts and correction notes. Audio, pronunciation, pauses and speaking fluency are not evaluated.'
        : 'This report uses saved session evidence and was not generated by AI.'}</p>
    </section>

    {(session || turnsUnavailable) && <section className="min-w-0 rounded-xl border bg-card p-5 shadow-sm sm:p-7" aria-labelledby="turns-title">
      <h2 id="turns-title" className="text-lg font-semibold">Conversation, turn by turn</h2>
      <p className="mt-2 text-sm leading-6 text-muted-foreground">A turn is one completed speaking attempt. “Recognized speech” is the automatic speech-to-text (STT) text saved for that attempt; it is the evidence used for language feedback and may differ from what you actually said. “Coach response” is the reply to that turn.</p>
      <p className="mt-2 text-sm leading-6 text-muted-foreground">Turn numbers in the report refer to the rows below. The report evaluates recognized text, not the audio itself.</p>
      {turnsUnavailable ? <p className="mt-4 rounded-lg border border-dashed p-4 text-sm text-muted-foreground" role="status">The saved report is available, but the turn-by-turn transcript could not be loaded.</p>
        : session && session.turns.length > 0 ? <div className="mt-4 max-h-[34rem] overflow-auto rounded-lg border">
          <table className="w-full min-w-[48rem] table-fixed border-collapse text-left text-sm">
            <caption className="sr-only">Recognized learner speech and coach responses, in completed-turn order</caption>
            <thead className="sticky top-0 z-10 bg-muted text-foreground"><tr>
              <th className="w-[10%] border-b px-4 py-3 font-semibold" scope="col">Turn</th>
              <th className="w-1/2 border-b px-4 py-3 font-semibold" scope="col">Recognized speech (STT)</th>
              <th className="w-1/2 border-b px-4 py-3 font-semibold" scope="col">Coach response</th>
            </tr></thead>
            <tbody>{session.turns.map(turn => <tr id={`turn-${turn.sequence}`} key={turn.sequence} className="align-top even:bg-muted/30">
              <th className="border-b px-4 py-4 font-semibold text-muted-foreground" scope="row">{turn.sequence}</th>
              <td className="whitespace-pre-wrap border-b px-4 py-4 leading-6">{turn.transcript || <span className="italic text-muted-foreground">No recognized text was saved for this turn.</span>}</td>
              <td className="whitespace-pre-wrap border-b px-4 py-4 leading-6">{turn.assistantResponse || <span className="italic text-muted-foreground">No coach response was saved.</span>}</td>
            </tr>)}</tbody>
          </table>
        </div> : <p className="mt-4 rounded-lg border border-dashed p-4 text-sm text-muted-foreground">No completed speaking turns were saved for this session.</p>}
    </section>}

    <ParameterCoverageView coverage={report.parameterCoverage} turnLinksAvailable={Boolean(session && !turnsUnavailable)} />

    {!learningSupport && <section className="min-w-0 rounded-xl border bg-primary/5 p-5 sm:p-6" aria-labelledby="english-support-title">
      <h2 id="english-support-title" className="text-lg font-semibold">English learning support</h2>
      <p className="mt-2 text-sm leading-6 text-muted-foreground">Prepare English suggestions, observations and next steps from your saved session, with Spanish translations and explanations. Your original report stays saved.</p>
      {onLoadSupport && <Button type="button" className="mt-4" disabled={supportLoading} onClick={onLoadSupport}>{supportLoading ? 'Preparing English version…' : 'Prepare English version'}</Button>}
      {supportLoading && <p className="mt-3 text-sm text-muted-foreground" role="status">Preparing your bilingual learning support. No new recording is needed.</p>}
      {supportError && <p className="mt-3 text-sm text-destructive" role="alert">{supportError}</p>}
    </section>}

    <section className="min-w-0 rounded-xl border bg-card p-5 shadow-sm sm:p-7" aria-labelledby="corrections-title">
      <div><h2 id="corrections-title" className="text-lg font-semibold">Corrections tied to your transcript</h2>
        <p className="mt-1 text-sm leading-6 text-muted-foreground">The “recognized text” column is what STT captured. Suggestions are linked to the numbered conversation turns above.</p></div>
      {(learningSupport ? learningSupport.corrections.length > 0 : report.corrections.length > 0) ? <div className="mt-4 overflow-x-auto rounded-lg border">
        <table className="w-full min-w-[52rem] table-fixed border-collapse text-left text-sm">
          <caption className="sr-only">Evidence-backed language suggestions linked to completed speaking turns</caption>
          <thead className="bg-muted"><tr>
            <th className="w-[10%] border-b px-4 py-3 font-semibold" scope="col">Turn</th>
            <th className="w-[30%] border-b px-4 py-3 font-semibold" scope="col">Recognized text (STT)</th>
            <th className="w-[30%] border-b px-4 py-3 font-semibold" scope="col">Suggested wording (English)</th>
            <th className="w-[30%] border-b px-4 py-3 font-semibold" scope="col">Why</th>
          </tr></thead>
          <tbody>{(learningSupport ? learningSupport.corrections : report.corrections).map(correction => {
            const support = 'suggestedEnglish' in correction ? correction : null;
            const saved = report.corrections.find(item => item.sequence === correction.sequence);
            const original = saved?.original ?? session?.turns.find(turn => turn.sequence === correction.sequence)?.transcript;
            return <tr key={correction.sequence} className="align-top even:bg-muted/30">
              <th className="border-b px-4 py-4 font-semibold text-muted-foreground" scope="row">{session && !turnsUnavailable ? <a className="text-primary underline underline-offset-2" href={`#turn-${correction.sequence}`}>Turn {correction.sequence}</a> : `Turn ${correction.sequence}`}</th>
              <td className="whitespace-pre-wrap border-b px-4 py-4 leading-6">{original ?? 'The original text is unavailable.'}</td>
              <td className="border-b px-4 py-3 leading-6">{support ? <div className="flex items-start gap-2">
                <p lang="en" className="min-w-0 whitespace-pre-wrap">{support.suggestedEnglish}</p>
                <ReportSpeechButton text={support.suggestedEnglish} language="en" label={`Listen to suggestion for turn ${correction.sequence}`} />
              </div> : <div className="grid gap-2"><p className="text-muted-foreground">Prepare the English version to see a suggested phrase.</p>
                {saved && <details className="rounded-lg border p-3"><summary className="cursor-pointer text-sm font-medium">Saved wording · Español</summary><p lang="es" className="mt-2 whitespace-pre-wrap">{saved.correctedPhrase}</p></details>}
              </div>}</td>
              <td className="border-b px-4 py-3 leading-6">{support ? <div className="flex items-start gap-2">
                <p lang="en" className="min-w-0 whitespace-pre-wrap">{support.explanationEn}</p>
                <ReportSpanishExplanation title={`Turn ${correction.sequence}`} translation={support.translationEs} explanations={[support.explanationEs]} label="Traducción y explicación" />
              </div> : saved && <details className="rounded-lg border p-3"><summary className="cursor-pointer font-medium">Saved explanation · Español</summary><p lang="es" className="mt-2 whitespace-pre-wrap">{saved.explanation}</p></details>}</td>
            </tr>;
          })}</tbody>
        </table>
      </div> : <p className="mt-4 rounded-lg border border-dashed p-4 text-sm leading-6 text-muted-foreground">No evidence-backed corrections were available for this session.</p>}
    </section>

    <div className="grid min-w-0 gap-4 @min-[40rem]/report:grid-cols-2">
      <ReportLearningNotes id="strengths-title" title="Observed strengths" notes={learningSupport?.strengths} legacyNotes={report.strengths} turnLinksAvailable={Boolean(session && !turnsUnavailable)} emptyMessage="There was not enough completed-turn evidence to identify strengths." />
      <ReportLearningNotes id="recommendations-title" title="Next practice" notes={learningSupport?.recommendations} legacyNotes={report.recommendations} turnLinksAvailable={Boolean(session && !turnsUnavailable)} emptyMessage="No additional recommendations are available for this session." />
    </div>

    {session && <section className="min-w-0 rounded-xl border bg-primary/5 p-5 sm:p-6" aria-labelledby="video-title">
      <h2 id="video-title" className="text-lg font-semibold">Keep practicing with a related video</h2>
      <p className="mt-2 text-sm leading-6 text-muted-foreground">Find English conversation videos about {topicSearchTerms[session.topic]} at your target level ({session.level}){report.parameterCoverage?.length ? ', with your practice goals included in the search' : ''}. YouTube opens in a new tab.</p>
      <a className="mt-4 inline-flex min-h-10 items-center gap-2 rounded-4xl bg-primary px-4 text-sm font-medium text-primary-foreground outline-none hover:bg-primary/80 focus-visible:ring-[3px] focus-visible:ring-ring/50" href={youtubeSearchUrl(session, report)} target="_blank" rel="noopener noreferrer">Find a related video on YouTube <ArrowUpRight className="size-4" aria-hidden="true" /></a>
    </section>}
  </div>;
}

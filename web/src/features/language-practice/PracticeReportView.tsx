import { useEffect, useMemo, useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import { authSession } from '../../auth-session';
import {
  LanguagePracticeClient,
  LanguagePracticeClientError,
  type LanguagePracticeClientErrorKind,
  type LanguagePracticeReport,
} from './language-practice-client';

export function PracticeReportView() {
  const { sessionId = '' } = useParams<{ sessionId: string }>();
  const client = useMemo(() => new LanguagePracticeClient(authSession), []);
  const [report, setReport] = useState<LanguagePracticeReport | null>(null);
  const [loading, setLoading] = useState(true);
  const [errorKind, setErrorKind] = useState<LanguagePracticeClientErrorKind | null>(null);
  const [attempt, setAttempt] = useState(0);

  useEffect(() => {
    let disposed = false;
    setReport(null);
    setLoading(true);
    setErrorKind(null);

    async function loadReport() {
      try {
        const result = await client.getOrCreateReport(sessionId);
        if (!disposed) setReport(result);
      } catch (error) {
        if (!disposed) {
          setErrorKind(error instanceof LanguagePracticeClientError ? error.kind : 'unavailable');
        }
      } finally {
        if (!disposed) setLoading(false);
      }
    }

    void loadReport();
    return () => { disposed = true; };
  }, [attempt, client, sessionId]);

  const canRetry = errorKind !== null && errorKind !== 'conflict' && errorKind !== 'not-found' && errorKind !== 'invalid-input';

  return (
    <main className="mx-auto w-full max-w-3xl px-4 py-8 sm:px-6 sm:py-12" aria-labelledby="report-title">
      <header className="mb-7 sm:mb-8">
        <p className="mb-2 text-xs font-semibold uppercase tracking-[0.14em] text-primary">Practice complete</p>
        <h1 id="report-title" className="text-3xl font-semibold tracking-tight sm:text-4xl">Your practice report</h1>
        <p className="mt-2 max-w-xl text-sm leading-6 text-muted-foreground">Review saved evidence from your session and choose what to practice next.</p>
      </header>

      {loading && <section className="rounded-xl border bg-card p-5 text-sm text-muted-foreground shadow-sm sm:p-7" role="status" aria-live="polite">Preparing your report…</section>}

      {!loading && errorKind && <section className="grid gap-3 rounded-xl border border-destructive/30 bg-destructive/5 p-5 text-sm sm:p-7" role="alert">
        <h2 className="text-lg font-semibold">We could not load your report</h2>
        {errorKind === 'conflict' ? <p className="leading-6">This session is still in progress. Return to your session and finish practicing before viewing its report.</p> :
          errorKind === 'not-found' ? <p className="leading-6">This practice session could not be found. Return to setup to start a new practice session.</p> :
            errorKind === 'invalid-input' ? <p className="leading-6">This session link is not valid. Return to setup to start a new practice session.</p> :
              <p className="leading-6">The session remains saved. You can try loading its report again.</p>}
        {errorKind === 'conflict' && <Link className="inline-flex min-h-10 w-fit items-center justify-center rounded-4xl border bg-input/30 px-4 text-sm font-medium outline-none hover:bg-input/50 focus-visible:ring-[3px] focus-visible:ring-ring/50" to={`/language-practice/sessions/${sessionId}`}>Return to session</Link>}
        {canRetry && <button type="button" className="inline-flex min-h-10 w-fit items-center justify-center rounded-4xl border bg-input/30 px-4 text-sm font-medium outline-none hover:bg-input/50 focus-visible:ring-[3px] focus-visible:ring-ring/50 disabled:pointer-events-none disabled:opacity-50" disabled={loading} onClick={() => setAttempt((current) => current + 1)}>Try again</button>}
      </section>}

      {!loading && report && <>
        <section className="rounded-xl border bg-card p-5 shadow-sm sm:p-7" aria-labelledby="summary-title">
          <h2 id="summary-title" className="text-lg font-semibold">Performance summary</h2>
          <p className="mt-3 text-sm leading-6 text-muted-foreground">{report.summary}</p>
          <p className="mt-4 border-t pt-4 text-sm leading-6 text-muted-foreground">{report.generatedWithAi
            ? 'This new report was drafted with AI from saved session evidence.'
            : 'This historical report is generated from saved session evidence and was not generated by AI.'}</p>
        </section>

        <section className="mt-6 grid gap-4" aria-labelledby="corrections-title">
          <div>
            <h2 id="corrections-title" className="text-lg font-semibold">Corrections from your turns</h2>
            <p className="mt-1 text-sm leading-6 text-muted-foreground">Only corrections supported by saved session evidence appear here.</p>
          </div>
          {report.corrections.length > 0 ? <div className="grid gap-4">
            {report.corrections.map((correction) => <article key={correction.sequence} className="rounded-xl border bg-card p-5 shadow-sm sm:p-6">
              <p className="mb-3 text-xs font-semibold uppercase tracking-[0.14em] text-primary">Turn {correction.sequence}</p>
              <dl className="grid gap-4 sm:grid-cols-3">
                <div className="min-w-0"><dt className="text-sm font-semibold text-muted-foreground">Original</dt><dd className="mt-1 break-words text-sm leading-6">{correction.original}</dd></div>
                <div className="min-w-0"><dt className="text-sm font-semibold text-muted-foreground">Coach suggestion (Spanish)</dt><dd className="mt-1 break-words text-sm leading-6">{correction.correctedPhrase}</dd></div>
                <div className="min-w-0"><dt className="text-sm font-semibold text-muted-foreground">Explanation</dt><dd className="mt-1 break-words text-sm leading-6">{correction.explanation}</dd></div>
              </dl>
            </article>)}
          </div> : <p className="rounded-xl border border-dashed p-5 text-sm leading-6 text-muted-foreground">No evidence-backed corrections were available for this session.</p>}
        </section>

        <div className="mt-6 grid gap-4 sm:grid-cols-2">
          <section className="rounded-xl border bg-card p-5 shadow-sm sm:p-6" aria-labelledby="strengths-title">
            <h2 id="strengths-title" className="text-lg font-semibold">Observed strengths</h2>
            {report.strengths.length > 0 ? <ul className="mt-3 grid gap-2 pl-5 text-sm leading-6">{report.strengths.map((strength) => <li key={strength}>{strength}</li>)}</ul> : <p className="mt-3 text-sm leading-6 text-muted-foreground">There was not enough completed-turn evidence to identify strengths.</p>}
          </section>
          <section className="rounded-xl border bg-card p-5 shadow-sm sm:p-6" aria-labelledby="recommendations-title">
            <h2 id="recommendations-title" className="text-lg font-semibold">Next practice</h2>
            {report.recommendations.length > 0 ? <ul className="mt-3 grid gap-2 pl-5 text-sm leading-6">{report.recommendations.map((recommendation) => <li key={recommendation}>{recommendation}</li>)}</ul> : <p className="mt-3 text-sm leading-6 text-muted-foreground">No additional recommendations are available for this session.</p>}
          </section>
        </div>
      </>}

      {!loading && !report && !errorKind && <p className="rounded-xl border border-dashed p-5 text-center text-sm text-muted-foreground" role="status">No report is available for this session.</p>}

      <nav className="mt-6" aria-label="Practice navigation">
        <Link className="inline-flex min-h-10 items-center justify-center rounded-4xl bg-primary px-4 text-sm font-medium text-primary-foreground outline-none hover:bg-primary/80 focus-visible:ring-[3px] focus-visible:ring-ring/50" to="/language-practice">Return to practice setup</Link>
      </nav>
    </main>
  );
}

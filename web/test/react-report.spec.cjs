const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const viewPath = path.join(__dirname, '../src/features/language-practice/PracticeReportView.tsx');
const view = fs.existsSync(viewPath) ? fs.readFileSync(viewPath, 'utf8') : '';
const routes = fs.readFileSync(path.join(__dirname, '../src/react-routes.tsx'), 'utf8');

test('renders evidence-backed report sections and bounded-list empty states', () => {
  for (const phrase of [
    'Your practice report', 'Performance summary', 'Corrections from your turns', 'Original',
    'Suggested correction', 'Explanation', 'Observed strengths', 'Next practice',
    'No evidence-backed corrections', 'not generated by AI',
  ]) assert.ok(view.includes(phrase), `missing report UI copy: ${phrase}`);
  assert.match(view, /report\.corrections\.length/);
  assert.match(view, /report\.strengths\.length/);
  assert.match(view, /report\.recommendations\.length/);
  assert.match(view, /max-w-3xl|mx-auto/);
  assert.match(view, /getOrCreateReport\(sessionId\)/);
  assert.doesNotMatch(view, /localStorage|sessionStorage|speechSynthesis|synthesize|transcribe/i);
});

test('loads once, prevents overlapping requests, and retries a failed report request', () => {
  assert.match(view, /new LanguagePracticeClient\(authSession\)/);
  assert.match(view, /useEffect\(\(\) => \{/);
  assert.match(view, /void loadReport\(\)/);
  assert.match(view, /return \(\) => \{ disposed = true; \};/);
  assert.match(view, /\[attempt, client, sessionId\]/);
  assert.match(view, /setAttempt\(\(current\) => current \+ 1\)/);
  assert.match(view, /Try again/);
  assert.match(view, /role="status"/);
});

test('shows distinct safe recovery guidance and actions for each report error kind', () => {
  assert.match(view, /errorKind === 'conflict'/);
  assert.match(view, /`\/language-practice\/sessions\/\$\{sessionId\}`/);
  assert.match(view, /This session is still in progress\. Return to your session and finish practicing before viewing its report\./);
  assert.match(view, /This practice session could not be found\. Return to setup to start a new practice session\./);
  assert.match(view, /This session link is not valid\. Return to setup to start a new practice session\./);
  assert.match(view, /The session remains saved\. You can try loading its report again\./);
  assert.match(view, /errorKind !== 'conflict' && errorKind !== 'not-found' && errorKind !== 'invalid-input'/);
  assert.match(view, /errorKind !== 'not-found' && errorKind !== 'invalid-input'/);
  assert.match(view, /role="alert"/);
  assert.match(view, /Return to practice setup/);
  assert.match(view, /setErrorKind\(error instanceof LanguagePracticeClientError \? error\.kind : 'unavailable'\)/);
  assert.doesNotMatch(view, /error\.message|publicMessage/);
});

test('keeps completed and live session routes behind authentication gating', () => {
  assert.match(routes, /<Route path="\/language-practice\/sessions\/\:sessionId\/complete" element=\{\s*<RouteGate><PracticeReportView \/><\/RouteGate>/);
  assert.match(routes, /<RouteGate><LivePracticeView \/><\/RouteGate>/);
  assert.match(routes, /<RouteGate><LanguagePracticeSetupView \/><\/RouteGate>/);
});

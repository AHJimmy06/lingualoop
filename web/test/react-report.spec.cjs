const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const viewPath = path.join(__dirname, '../src/features/language-practice/PracticeReportView.tsx');
const routeView = fs.existsSync(viewPath) ? fs.readFileSync(viewPath, 'utf8') : '';
const content = fs.readFileSync(path.join(__dirname, '../src/features/language-practice/PracticeReportContent.tsx'), 'utf8');
const view = routeView + content;
const routes = fs.readFileSync(path.join(__dirname, '../src/react-routes.tsx'), 'utf8');

test('renders evidence-backed report sections and bounded-list empty states', () => {
  for (const phrase of [
    'Your practice report', 'Performance summary', 'Corrections tied to your transcript',
    'Recognized speech (STT)', 'Coach response', 'Suggested wording', 'Observed strengths', 'Next practice',
    'No evidence-backed corrections', 'Keep practicing with a related video',
  ]) assert.ok(view.includes(phrase), `missing report UI copy: ${phrase}`);
  assert.match(view, /report\.corrections\.length/);
  assert.match(content, /legacyNotes=\{report\.strengths\}/);
  assert.match(content, /legacyNotes=\{report\.recommendations\}/);
  assert.match(view, /report\.generatedWithAi/);
  assert.match(view, /AI observations use saved STT transcripts and correction notes/);
  assert.match(view, /generated by AI/);
  assert.match(view, /not generated by AI/);
  assert.match(view, /A turn is one completed speaking attempt/);
  assert.match(view, /may differ from what you actually said/);
  assert.match(view, /youtube\.com\/results\?search_query=/);
  assert.match(content, /youtubeSearchUrl\(session, report\)/);
  assert.match(content, /report\.parameterCoverage \?\? \[\]/);
  assert.match(content, /map\(value => value\.normalize\('NFKC'\)/);
  assert.match(content, /practice goals included in the search/);
  assert.match(content, /target="_blank" rel="noopener noreferrer"/);
  assert.doesNotMatch(view, /Suggested correction/);
  assert.match(routeView, /<main className="authenticated-page \[overflow-wrap:anywhere\]"/);
  assert.doesNotMatch(routeView, /max-w-3xl|max-w-5xl/);
  assert.doesNotMatch(content, /\[&_p\]:max-w-prose|\[&_dd\]:max-w-prose|\[&_ul\]:max-w-prose/);
  assert.match(view, /getCompleteReport\(sessionId\)/);
  assert.match(routeView, /<PracticeReportContent report=\{report\} session=\{session\} learningSupport=\{learningSupport\}/);
  assert.doesNotMatch(content, /authSession|getOrCreateReport|fetch\(/);
  assert.match(content, /<ReportSpeechButton text=\{support\.suggestedEnglish\} language="en"/);
  assert.doesNotMatch(content, /Saved wording · Español/);
  assert.doesNotMatch(content, /<ReportSpanishExplanation/);
  assert.doesNotMatch(view, /localStorage|sessionStorage|speechSynthesis|synthesize|transcribe/i);
});

test('report transcript, corrections, and requirement coverage use labeled tables', () => {
  assert.match(content, /@container\/report grid min-w-0 gap-6 \[overflow-wrap:anywhere\]/);
  assert.match(content, /<ParameterCoverageView coverage=\{report\.parameterCoverage\}/);
  assert.match(content, /<table className="w-full min-w-\[48rem\] table-fixed/);
  assert.match(content, /<table className="w-full min-w-\[52rem\] table-fixed/);
  assert.match(content, /id=\{`turn-\$\{turn\.sequence\}`\}/);
  assert.match(content, /text saved for that attempt/);
  const coverage = fs.readFileSync(path.join(__dirname, '../src/features/language-practice/ParameterCoverageView.tsx'), 'utf8');
  assert.match(coverage, /<table className="w-full min-w-\[48rem\] table-fixed/);
  assert.match(coverage, /A turn number is the order of a completed student speaking attempt/);
  assert.match(coverage, /Not assessed\. This is not a failed requirement/);
  assert.match(coverage, /href=\{`#turn-\$\{sequence\}`\}/);
  assert.doesNotMatch(content, /sm:grid-cols|lg:grid-cols|useEffect|fetch\(|authSession|Client/);
  assert.doesNotMatch(coverage, /useEffect|fetch\(|authSession|Client/);
});

test('loads once, prevents overlapping requests, and retries a failed report request', () => {
  assert.match(routeView, /Your browser is offline/);
  assert.match(routeView, /disabled=\{loading \|\| offline\}/);
  assert.match(routeView, /addEventListener\('online', updateConnection\)/);
  assert.match(routeView, /removeEventListener\('offline', updateConnection\)/);
  assert.match(view, /new LanguagePracticeClient\(authSession\)/);
  assert.match(view, /useEffect\(\(\) => \{/);
  assert.match(view, /void loadReport\(\)/);
  assert.match(view, /await client\.getCompleteReport\(sessionId\)/);
  assert.doesNotMatch(routeView, /getCachedReportLearningSupport|prepareReportLearningSupport|Prepare English version/);
  assert.match(view, /return \(\) => \{ disposed = true; \};/);
  assert.match(view, /\[attempt, client, sessionId\]/);
  assert.match(view, /setAttempt\(\(current\) => current \+ 1\)/);
  assert.match(view, /Try again/);
  assert.match(view, /role="status"/);
});

test('shows distinct safe recovery guidance and actions for each report error kind', () => {
  assert.match(view, /errorKind === 'conflict'/);
  assert.match(view, /`\/language-practice\/sessions\/\$\{sessionId\}`/);
  assert.match(view, /This session is still in progress\. Return to your session and finish practicing before viewing its report\./);
  assert.match(view, /This practice session could not be found\. Return to setup to start a new practice session\./);
  assert.match(view, /This session link is not valid\. Return to setup to start a new practice session\./);
  assert.match(view, /The session remains saved\. The complete report is not ready yet\. Try again to finish preparing it\./);
  assert.match(view, /errorKind !== 'conflict' && errorKind !== 'not-found' && errorKind !== 'invalid-input'/);
  assert.match(view, /errorKind !== 'not-found' && errorKind !== 'invalid-input'/);
  assert.match(view, /role="alert"/);
  assert.match(view, /Return to practice setup/);
  assert.match(view, /setErrorKind\(cause instanceof LanguagePracticeClientError \? cause\.kind : 'unavailable'\)/);
  assert.doesNotMatch(view, /error\.message|publicMessage/);
});

test('keeps completed and live session routes behind authentication gating', () => {
  assert.match(routes, /<Route path="\/language-practice\/sessions\/\:sessionId\/complete" element=\{\s*<RouteGate><PracticeReportView \/><\/RouteGate>/);
  assert.match(routes, /<RouteGate><LivePracticeView \/><\/RouteGate>/);
  assert.match(routes, /<RouteGate><LanguagePracticeSetupView \/><\/RouteGate>/);
});

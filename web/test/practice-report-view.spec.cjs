const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const viewPath = path.join(__dirname, '../src/features/language-practice/PracticeReportView.vue');
const source = fs.readFileSync(viewPath, 'utf8');
const script = source.match(/<script setup lang="ts">([\s\S]*?)<\/script>/)?.[1] ?? '';
const templateStart = source.indexOf('<template>') + '<template>'.length;
const templateEnd = source.lastIndexOf('</template>');
const template = templateStart >= '<template>'.length && templateEnd >= templateStart
  ? source.slice(templateStart, templateEnd)
  : '';

test('loads the typed deterministic report once on mount and retries only after failure', () => {
  assert.match(script, /new LanguagePracticeClient\(authSession\)/);
  assert.match(script, /client\.getOrCreateReport\(sessionId\.value\)/);
  assert.match(script, /onMounted\(\(\) => \{ void loadReport\(\) \}\)/);
  assert.match(script, /if \(disposed \|\| requestInFlight \|\| report\.value\) return/);
  assert.match(script, /function retry\(\): void \{\s*if \(errorKind\.value !== null\) void loadReport\(\)/);
  assert.match(script, /onBeforeUnmount\(\(\) => \{ disposed = true \}\)/);
  assert.match(script, /const value = route\.params\.sessionId/);
});

test('renders evidence sections, honest deterministic status, empty states, and error-specific navigation', () => {
  for (const phrase of [
    'Performance summary', 'Corrections from your turns', 'Original', 'Suggested correction', 'Explanation',
    'Observed strengths', 'Next practice', 'No evidence-backed corrections', 'not generated by AI',
    'Return to practice setup', 'Return to session',
  ]) assert.ok(template.includes(phrase), `missing report UI copy: ${phrase}`);
  assert.match(template, /errorKind === 'conflict'[\s\S]*?Return to your session/);
  assert.match(template, /errorKind === 'not-found'[\s\S]*?Return to setup/);
  assert.match(template, /<RouterLink v-if="errorKind === 'conflict'" :to="`\/language-practice\/sessions\/\$\{sessionId\}`"[^>]*>Return to session<\/RouterLink>/);
  assert.doesNotMatch(source, /router\.back\(\)|useRouter/);
  assert.match(template, /report\.corrections\.length/);
  assert.match(template, /report\.strengths\.length/);
  assert.match(template, /report\.recommendations\.length/);
});

test('does not make report calls outside LanguagePracticeClient or add speech controls', () => {
  assert.equal((script.match(/getOrCreateReport\(/g) ?? []).length, 1);
  assert.doesNotMatch(source, /localStorage|sessionStorage|speechSynthesis|synthesize|transcribe/i);
  assert.doesNotMatch(template, /<audio\b|text-to-speech|speak aloud/i);
});
